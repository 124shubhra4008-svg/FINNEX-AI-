@app.get("/insights/investment")
def investment_plan(user_id: int = Depends(auth.get_current_user_id)):
    user = db.get_user_by_id(user_id)
    tx = db.get_transactions(user_id)
    totals = fe.monthly_totals(tx)
    if totals:
        latest = list(totals.values())[-1]
        surplus = max(0, latest["income"] - latest["expense"])
    else:
        surplus = 0
    return fe.investment_allocation(user["risk_profile"], surplus)


@app.get("/insights/dashboard")
def dashboard_summary(user_id: int = Depends(auth.get_current_user_id)):
    """One-shot endpoint the frontend dashboard calls to minimize round trips."""
    tx = db.get_transactions(user_id)
    budgets = db.get_budgets(user_id)
    goals = db.get_goals(user_id)
    bills = db.get_bills(user_id)
    accounts = db.get_account_balances(user_id)
    return {
        "monthly_totals": fe.monthly_totals(tx),
        "health_score": fe.financial_health_score(tx, budgets, goals),
        "prediction": fe.predict_month_end_expense(tx),
        "subscriptions": fe.detect_subscriptions(tx),
        "budgets": budgets,
        "goals": goals,
        "upcoming_bills": [b for b in bills if not b["paid"]],
        "due_soon_bills": db.get_due_soon_bills(user_id, 7),
        "accounts": accounts,
        "total_balance": round(sum(a["balance"] for a in accounts), 2),
        "recent_transactions": tx[:10],
    }


