@app.post("/auth/signup", response_model=TokenResponse)
def signup(payload: SignupRequest):
    if db.get_user_by_email(payload.email):
        raise HTTPException(status_code=400, detail="An account with this email already exists.")
    pw_hash, salt = auth.hash_password(payload.password)
    user_id = db.create_user(payload.email, payload.name, pw_hash, salt)
    token = auth.create_token(user_id, payload.email)
    return {"access_token": token, "user": {"id": user_id, "name": payload.name, "email": payload.email}}


@app.post("/auth/login", response_model=TokenResponse)
def login(payload: LoginRequest):
    user = db.get_user_by_email(payload.email)
    if not user or not auth.verify_password(payload.password, user["password_hash"], user["salt"]):
        raise HTTPException(status_code=401, detail="Invalid email or password.")
    token = auth.create_token(user["id"], user["email"])
    return {"access_token": token, "user": {"id": user["id"], "name": user["name"], "email": user["email"]}}


