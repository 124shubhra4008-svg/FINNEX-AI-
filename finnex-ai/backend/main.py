# ---- Import your own file (CSV) --------------------------------------
# Upload once with POST /transactions/import, then every row it added is
# tagged with one shared batch id. GET the history to show past imports,
# and DELETE a batch id to undo that whole import in one go without
# touching anything else (manual entries or other imports).

@app.post("/transactions/import")
async def import_transactions(
    file: UploadFile = File(...),
    account_id: int = None,
    user_id: int = Depends(auth.get_current_user_id),
):
    raw = await file.read()
    if not raw:
        raise HTTPException(status_code=400, detail="The uploaded file is empty.")

    try:
        rows, parse_errors = transaction_import.parse_transactions_csv(raw)
    except ValueError as e:
        raise HTTPException(status_code=422, detail=str(e))

    if not rows:
        raise HTTPException(
            status_code=422,
            detail="No valid rows could be imported. " + " ".join(parse_errors[:5]),
        )

    batch_id = uuid.uuid4().hex
    for row in rows:
        db.add_transaction(
            user_id, row["date"], row["type"], row["category"], row["merchant"],
            row["description"], row["amount"], row["is_recurring"], account_id,
            import_batch_id=batch_id, import_filename=file.filename,
        )

    return {
        "batch_id": batch_id,
        "filename": file.filename,
        "imported": len(rows),
        "skipped": len(parse_errors),
        "errors": parse_errors[:20],  # cap so a bad file doesn't flood the response
    }


@app.get("/transactions/import/history")
def import_history(user_id: int = Depends(auth.get_current_user_id)):
    return db.get_import_batches(user_id)


@app.delete("/transactions/import/{batch_id}")
def undo_import(batch_id: str, user_id: int = Depends(auth.get_current_user_id)):
    removed = db.delete_import_batch(user_id, batch_id)
    if removed == 0:
        raise HTTPException(status_code=404, detail="Import batch not found.")
    return {"success": True, "removed": removed}


